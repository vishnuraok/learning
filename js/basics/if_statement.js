// Demonstrating the use of if statements in JavaScript
// Assigning a value to a variable
let a_number = 10;

// Testing if the number is greater than 5
console.log("Testing if the number is greater than 5:");
if (a_number > 5) {
    console.log("The number is greater than 5");
} else {
    console.log("The number is not greater than 5");
}

// Testing if the number is equal to 10
console.log("Testing if the number is equal to 10:");
if (a_number === 10) {
    console.log("The number is equal to 10");
} else {
    console.log("The number is not equal to 10");
}

let a_string = "apple";

// Testing if the fruit is "apple"
console.log("Testing if the fruit is apple:");
if (a_string === "apple") {
    console.log("The fruit is an apple");
} else {
    console.log("The fruit is not an apple");
}
